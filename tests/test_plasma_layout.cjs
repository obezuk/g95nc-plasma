const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const layout = {};
vm.createContext(layout);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../plasma/com.obezuk.g95nc/contents/ui/Layout.js'), 'utf8'), layout);
const profiles = {single: {widths: [100]}, split: {widths: [50, 50]}, triple: {widths: [33, 33, 33]}};
const inputs = ['DisplayPort', 'HDMI1', 'HDMI2', 'HDMI3'];
const normalize = value => JSON.parse(JSON.stringify(value));
const draft = {profile: 'split', inputs: ['DisplayPort', 'HDMI1']};
assert.deepEqual(normalize(layout.assign(draft, 0, 'HDMI1')), {profile: 'split', inputs: ['HDMI1', 'DisplayPort']});
assert.deepEqual(draft.inputs, ['DisplayPort', 'HDMI1']);
assert.deepEqual(normalize(layout.choose('triple', draft, profiles, inputs)).inputs, ['DisplayPort', 'HDMI1', 'HDMI2']);
assert.deepEqual(normalize(layout.choose('single', draft, profiles, inputs)).inputs, ['DisplayPort']);
assert.equal(layout.valid({profile: 'split', inputs: ['HDMI1', 'HDMI1']}, profiles, inputs), false);
assert.equal(layout.valid({profile: 'split', inputs: ['HDMI1']}, profiles, inputs), false);
assert.equal(layout.measured({profile: 'triple', panes: null}, profiles, inputs), null);
assert.equal(layout.measured({profile: 'triple', applied_layout: draft}, profiles, inputs), null);
assert.deepEqual(normalize(layout.measured({mode: 'single', input: 'DisplayPort'}, profiles, inputs)), {profile: 'single', inputs: ['DisplayPort']});
assert.equal(layout.same(draft, normalize(draft)), true);
assert.equal(layout.same(draft, null), false);
console.log('Plasma layout checks passed (no monitor access).');
const monitor = {};
vm.createContext(monitor);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../plasma/com.obezuk.g95nc/contents/ui/Monitor.js'), 'utf8'), monitor);
const catalog = monitor.profiles;
let edit = {profile: 'single', inputs: ['DisplayPort']};
edit = layout.drop(edit, 0, 'HDMI1', catalog, inputs);
assert.equal(edit.profile, '50-50');
edit = layout.choose('25-75', edit, catalog, inputs);
edit = layout.drop(edit, 1, 'HDMI2', catalog, inputs);
assert.equal(edit.profile, '33-33-33');
assert.deepEqual(normalize(edit.inputs), ['DisplayPort','HDMI1','HDMI2']);
edit = layout.snap(edit, 0, 50, catalog);
assert.equal(edit.profile, '50-25-25');
edit = layout.drop(edit, 2, 'DisplayPort', catalog, inputs);
assert.deepEqual(normalize(edit.inputs), ['HDMI2','HDMI1','DisplayPort']);
edit = layout.drop(edit, 1, 'HDMI3', catalog, inputs);
assert.equal(edit.inputs.length, 3);
assert.equal(edit.inputs[1], 'HDMI3');
edit = layout.remove(edit, 1, catalog);
assert.equal(edit.profile, '75-25');
edit = layout.remove(edit, 1, catalog);
assert.equal(edit.profile, 'single');
assert.equal(layout.remove(edit, 0, catalog).inputs.length, 1);
assert.equal(layout.drop({profile:'pip',inputs:['DisplayPort','HDMI1']},0,'HDMI2',catalog,inputs).profile,'25-25-50');
console.log('Dynamic input growth, targeted splitting, divider snapping, pane swaps, removal and PiP conversion passed.');
